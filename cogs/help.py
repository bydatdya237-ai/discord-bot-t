import discord
from discord.ext import commands


# =========================================================
# Cog
# =========================================================

class CommandsListCog(commands.Cog):

    def __init__(self, bot):
        self.bot = bot

    # =====================================================
    # أمر -اوامر
    # =====================================================

    @commands.command(
        name="اوامر",
        help="معرفة مكان عرض أوامر البوت."
    )
    async def commands_list(self, ctx):

        # -------------------------------------------------
        # يجب أن يكون داخل سيرفر
        # -------------------------------------------------

        if ctx.guild is None:
            return

        # -------------------------------------------------
        # الرد
        # -------------------------------------------------

        await ctx.send(
            "📚 **يمكنك معرفة جميع أوامر البوت من الموقع الرسمي للبوت.**",
            delete_after=10
        )

        # -------------------------------------------------
        # حذف رسالة -اوامر
        # -------------------------------------------------

        try:
            await ctx.message.delete()

        except discord.HTTPException:
            pass


# =========================================================
# Setup
# =========================================================

async def setup(bot):
    await bot.add_cog(
        CommandsListCog(bot)
    )
