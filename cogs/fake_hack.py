import asyncio
import discord
from discord.ext import commands


# =========================================================
# الإعدادات
# =========================================================

TRIGGER_TEXT = "وش ذا السيرفر"
WAIT_TIME = 30


# =========================================================
# Fake Hack Cog
# =========================================================

class FakeHackCog(commands.Cog):

    def __init__(self, bot):
        self.bot = bot

    @commands.Cog.listener()
    async def on_message(self, message):

        # تجاهل البوتات
        if message.author.bot:
            return

        # التحقق من الرسالة
        if message.content.strip() != TRIGGER_TEXT:
            return

        # =================================================
        # رسالة التخويف في الشات
        # =================================================

        await message.channel.send(
            f"⚠️ **جاري اختراق حسابك {message.author.mention}...**\n"
            "🔍 جاري فحص الحساب واستخراج المعلومات...\n"
            "⏳ الرجاء الانتظار..."
        )

        # =================================================
        # الانتظار 30 ثانية
        # =================================================

        await asyncio.sleep(WAIT_TIME)

        # =================================================
        # رسالة الخاص
        # =================================================

        dm_message = (
            "🚨 **تم اختراق حسابك** 🚨\n\n"
            "تم العثور على المعلومات التالية:\n\n"

            "👤 اسم الحساب: `........`\n"
            "🆔 معرف الحساب: `........`\n"
            "🏠 العنوان: `........`\n"
            "📍 الحي: `........`\n"
            "🌆 المدينة: `........`\n"
            "📱 رقم الجوال: `........`\n"
            "💻 معلومات الجهاز: `........`\n"
            "🌐 الموقع: `........`\n"
            "🔐 حالة الحساب: `........`\n\n"

            "📤 **تم إرسال معلوماتك لصاحب البوت عشان تعرف السيرفر.**\n\n"

            "━━━━━━━━━━━━━━━━━━━━\n"
            "😂 **تم الاختراق !**\n\n"
            " تم اختراق حسابك  تم الحصول على  معلومات منك.\n"
            "جميع البيانات الموجودة بالأعلى تم حفظها وتم إرسالها لصاحب البوت.\n"
            "━━━━━━━━━━━━━━━━━━━━"
        )

        # =================================================
        # إرسال الخاص
        # =================================================

        try:
            await message.author.send(dm_message)

        except discord.Forbidden:
            await message.channel.send(
                f"{message.author.mention} \n"
                "حاولت أرسل لك نتيجة الاختراق بالخاص، لكن رسائلك الخاصة مقفلة!"
            )

        except Exception as e:
            print(f"[FakeHack] Error: {e}")


# =========================================================
# Setup
# =========================================================

async def setup(bot):
    await bot.add_cog(FakeHackCog(bot))
