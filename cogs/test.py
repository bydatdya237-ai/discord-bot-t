import asyncio
import discord
from discord.ext import commands


# =========================================================
# الإعدادات
# =========================================================

COMMAND_ROOM_ID = 1546099690968457237

ALLOWED_ROLE_ID = 1544078469657530578


# =========================================================
# Cog
# =========================================================

class TestCog(commands.Cog):

    def __init__(self, bot):
        self.bot = bot

    # =====================================================
    # أمر تسفير الكل
    # =====================================================

    @commands.command(name="تسفير-الكل")
    async def tasfeer_all(self, ctx):

        # -------------------------------------------------
        # إذا كان الروم غلط، تجاهل الأمر نهائيًا
        # -------------------------------------------------

        if ctx.channel.id != COMMAND_ROOM_ID:
            return

        # -------------------------------------------------
        # إذا ما عنده الرتبة، تجاهل الأمر نهائيًا
        # -------------------------------------------------

        if not any(role.id == ALLOWED_ROLE_ID for role in ctx.author.roles):
            return

        # -------------------------------------------------
        # رسالة البداية
        # -------------------------------------------------

        await ctx.send(
            "⏳ **جاري الآن عملية تسفير الكل...**"
        )

        # -------------------------------------------------
        # انتظار 30 ثانية
        # -------------------------------------------------

        await asyncio.sleep(30)

        # -------------------------------------------------
        # المقلب 😂
        # -------------------------------------------------

        await ctx.send(
            "😂 **هههههههههههههههههههههههههههههه ياهطف صدقت**"
        )


# =========================================================
# Setup
# =========================================================

async def setup(bot):
    await bot.add_cog(TestCog(bot))
